import express from "express";
import { AddAnalytics, GetPostsCount, GetViewsCount, } from "./analytics.controller.js";
import { addAnalyticsSchema, getViewsQuerySchema, } from "./analytics.validation.js";
import JoiValidator from "../../lib/middleware/joiValidator.js";
import expressWrapper from "../../lib/wrappers/expressWrapper.js";
import auth from "../../lib/middleware/auth.js";
import JoiQueryValidator from "../../lib/middleware/joiQueryValidator.js";
const analyticsRouter = express.Router();
analyticsRouter.post("/add-analytics", JoiValidator(addAnalyticsSchema), expressWrapper(AddAnalytics));
analyticsRouter.get("/views", auth("admin"), JoiQueryValidator(getViewsQuerySchema), expressWrapper(GetViewsCount));
analyticsRouter.get("/posts", auth("admin"), expressWrapper(GetPostsCount));
export default analyticsRouter;
